"""
In-memory variable arrays
=========================
"""
from __future__ import annotations

from typing import TYPE_CHECKING, Any

import dask.array.core
import numpy

from .abc import (
    Variable,
    concat,
    masked,
    not_equal,
    read_attributes,
    read_compressor,
    read_dimensions,
)

if TYPE_CHECKING:
    from collections.abc import Sequence

    import zarr
    from zarr.core.buffer import NDArrayLikeOrScalar

    from ..codecs import Codec
    from ..meta import Attribute
    from ..type_hints import ArrayLike, NDArray, NDMaskedArray


def _as_numpy_array(
    arr: Any,
    *,
    fill_value: Any | None = None,
) -> tuple[NDArray, Any]:
    """Convert an array-like object to a NumPy array.

    Dask arrays are computed first. If the input is masked, its masked values
    are replaced using its fill value.

    Args:
        arr: The input array.
        fill_value: The expected fill value.

    Returns:
        The NumPy array and its fill value.

    Raises:
        ValueError: If a masked input uses a different fill value.
    """
    if isinstance(arr, dask.array.core.Array):
        arr = arr.compute()

    result: NDArray = numpy.asanyarray(arr)
    if isinstance(result, numpy.ma.MaskedArray):
        if fill_value is not None and not_equal(fill_value, result.fill_value):
            raise ValueError(
                f'The fill value {fill_value!r} does not match the fill value '
                f'{result.fill_value!r} of the array.')
        return numpy.ma.filled(result, result.fill_value), result.fill_value
    return result, fill_value


class Array(Variable):
    """A variable backed by an in-memory NumPy array.

    Args:
        name: The variable name.
        data: The variable data.
        dimensions: The variable dimensions.
        attrs: The variable attributes.
        compressor: The compression codec.
        fill_value: The fill value for uninitialized data and masking.
        filters: The filter codecs applied before writing data.
        filler: Whether the variable was generated by the library.
    """

    def __init__(self,
                 name: str,
                 data: ArrayLike[Any] | NDArrayLikeOrScalar,
                 dimensions: Sequence[str],
                 *,
                 attrs: Sequence[Attribute] | None = None,
                 compressor: Codec | None = None,
                 fill_value: Any | None = None,
                 filters: Sequence[Codec] | None = None,
                 filler: bool = False) -> None:
        array: NDArray
        array, fill_value = _as_numpy_array(data, fill_value=fill_value)
        super().__init__(name,
                         array,
                         dimensions,
                         attrs=attrs,
                         compressor=compressor,
                         fill_value=fill_value,
                         filters=filters,
                         filler=filler)

    @property
    def data(self) -> dask.array.core.Array:
        """Return the NumPy data wrapped in a Dask array.

        Values matching a defined fill value are masked.

        Returns:
            The Dask array.

        .. seealso::

            :attr:`Variable.array <zcollection.variable.abc.Variable.array>`
        """
        if self.fill_value is None:
            return dask.array.core.from_array(self.array)
        return masked(dask.array.core.from_array(self.array), self.fill_value)

    @property
    def values(self) -> NDArray | NDMaskedArray:
        """Return the variable values as a NumPy array.

        Values matching a defined fill value are masked.

        Returns:
            The variable values, masked if a fill value is defined.
        """
        return (self.array if self.fill_value is None else masked(
            self.array, self.fill_value))

    @values.setter
    def values(self, data: Any) -> None:
        """Replace the underlying NumPy array.

        Masked input values are replaced using their fill value, which also
        becomes the variable's fill value. Unmasked input leaves it unchanged.

        Args:
            data: The new data.

        Raises:
            ValueError: If the number of data dimensions does not match the
                variable dimensions, or if the masked input has an incompatible
                fill value.
        """
        if len(data.shape) != len(self.dimensions):
            raise ValueError('Data shape does not match variable dimensions')
        self.array, self.fill_value = _as_numpy_array(
            data, fill_value=self.fill_value)

    def persist(self, **_) -> Array:
        """Return the variable with its data already in memory.

        Returns:
            The unchanged variable.
        """
        return self

    def compute(self, **_) -> NDArray | NDMaskedArray:
        """Return the variable values as a NumPy array.

        Values matching a defined fill value are masked.
        """
        return self.values

    def fill(self) -> Array:
        """Fill the variable with its fill value, if one is defined.

        Returns:
            The variable, unchanged if no fill value is defined.
        """
        if self.fill_value is not None:
            self.array = numpy.full_like(self.array, self.fill_value)
        return self

    @classmethod
    def from_zarr(cls, array: zarr.Array, name: str, **kwargs) -> Array:
        """Create an eager variable by reading a Zarr array.

        Args:
            array: The Zarr array to read.
            name: The variable name.
            **kwargs: Accepted for compatibility with the base class; ignored.

        Returns:
            The new variable.
        """
        attrs, fill_value = read_attributes(array)
        return cls(name,
                   array[...],
                   read_dimensions(array),
                   attrs=attrs,
                   compressor=read_compressor(array),
                   fill_value=fill_value,
                   filters=tuple(array.filters or ()))

    def concat(self, other: Array | Sequence[Array], dim: str) -> Array:
        """Concatenate the variable with other NumPy-backed variables.

        Args:
            other: A variable or sequence of variables to concatenate.
            dim: The concatenation dimension.

        Returns:
            The concatenated variable.

        Raises:
            ValueError: If the sequence is empty or contains objects that are
                not :class:`Array` instances.
        """
        return concat(self, other, numpy.concatenate, dim)

    def __getitem__(self, key: Any) -> Any:
        """Return the values selected by an index or slice.

        Args:
            key: The index or slice.

        Returns:
            The selected NumPy values, masked if a fill value is defined.
        """
        return (self.array[key] if self.fill_value is None else masked(
            self.array[key], self.fill_value))

    def rechunk(self, **_) -> Array:
        """Return the variable without changing its chunks.

        Returns:
            The unchanged variable.
        """
        return self
