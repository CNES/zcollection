#: Dask getter function used by the task graph to read Zarr array blocks.
GETTER: Callable = dask.array.core.getter


def _blockdims_from_blockshape(
        shape: tuple[int, ...],
        chunks: tuple[int, ...]) -> tuple[tuple[int, ...], ...]:
    """Convert a block shape to Dask block dimensions."""
    return tuple(((chunk_item, ) * (shape_item // chunk_item) +
                  ((shape_item % chunk_item, ) if shape_item %
                   chunk_item else ()) if shape_item else (0, ))
                 for shape_item, chunk_item in zip(shape, chunks, strict=True))


def from_zarr_array(
    array: zarr.Array,
    shape: Sequence[int],
    chunks: Sequence[int],
    name: str,
    *,
    lock: bool = False,
    asarray=True,
    inline_array=True,
) -> dask.array.core.Array:
    """Create a Dask array from a Zarr array with the requested chunking.

    Args:
        array: The source Zarr array.
        shape: The resulting array shape.
        chunks: The resulting chunk shape.
        name: The Dask array name.
        lock: Whether to lock access to the underlying store.
        asarray: Whether to convert each loaded block with ``numpy.asarray``.
        inline_array: Whether to include the source array directly in each
            task rather than in a separate task.

    Returns:
        The resulting Dask array.
    """
    dsk: dask.highlevelgraph.HighLevelGraph
    normalized_chunks: tuple[tuple[int, ...], ...]

    normalized_chunks = sum(  # type: ignore[return-value]
        (_blockdims_from_blockshape(
            (shape_item, ),
            (chunk_item, )) if not isinstance(chunk_item, (tuple, list)) else
         (chunk_item, )
         for shape_item, chunk_item in zip(shape, chunks, strict=True)),
        (),
    )
    dsk = dask.array.core.graph_from_arraylike(
        array,
        normalized_chunks,
        shape,
        name,
        getitem=GETTER,
        lock=lock,
        asarray=asarray,
        dtype=array.dtype,
        inline_array=inline_array,
    )
    return dask.array.core.Array(dsk,
                                 name,
                                 normalized_chunks,
                                 meta=array,
                                 dtype=array.dtype)


def _as_dask_array(
    arr: Any,
    *,
    fill_value: Any | None = None,
) -> tuple[dask.array.core.Array, Any]:
    """Convert an array-like object to a Dask array.

    If the input is masked, replace masked values using its fill value.

    Args:
        arr: The input array.
        fill_value: The expected fill value.

    Returns:
        The Dask array and its fill value.

    Raises:
        ValueError: If a masked input uses a different fill value.
    """
    result: dask.array.core.Array = dask.array.core.asarray(arr)
    _meta: Any = result._meta
    if isinstance(_meta, numpy.ma.MaskedArray):
        if fill_value is not None and not_equal(fill_value, _meta.fill_value):
            raise ValueError(
                f'The fill value {fill_value!r} does not match the fill value '
                f'{_meta.fill_value!r} of the array.')
        return dask.array.ma.filled(result, _meta.fill_value), _meta.fill_value
    return result, fill_value


class ModifiedVariableError(RuntimeError):
    """Raised when a variable has changed since it was initialized."""

    def __str__(self) -> str:
        """Return the exception message.

        Returns:
            The message as a string.
        """
        return ('You tried to access the data of a variable that has been '
                'modified since its initialization. Try to re-load the '
                'dataset.')


class DelayedArray(Variable):
    """A variable backed by a Dask array.

    Args:
        name: The variable name.
        data: The variable data.
        dimensions: The variable dimensions.
        attrs: The variable attributes.
        compressor: The compression codec.
        fill_value: The fill value for uninitialized data and masking.
        filters: The filter codecs applied before writing data.
        filler: Whether the variable was generated by the library.
    """

    def __init__(self,
                 name: str,
                 data: ArrayLike[Any],
                 dimensions: Sequence[str],
                 *,
                 attrs: Sequence[Attribute] | None = None,
                 compressor: Codec | None = None,
                 fill_value: Any | None = None,
                 filters: Sequence[Codec] | None = None,
                 filler: bool = False) -> None:
        array: dask.array.core.Array
        array, fill_value = _as_dask_array(data, fill_value=fill_value)

        super().__init__(
            name,
            array,
            dimensions,
            attrs=attrs,
            compressor=compressor,
            fill_value=fill_value,
            filters=filters,
            filler=filler,
        )

    @property
    def data(self) -> dask.array.core.Array:
        """Return the underlying Dask array, masking fill values if defined.

        If no fill value is defined, or the array is already masked, the
        underlying array is returned directly.

        Returns:
            The Dask array.

        .. seealso::

            :attr:`Variable.array <zcollection.variable.abc.Variable.array>`
        """
        # Return the underlying array if no fill value is defined or if
        # its blocks already contain masked arrays.

        # No other way to check if the dask array is a masked array.
        if (self.fill_value is None
                or isinstance(self.array._meta, numpy.ma.MaskedArray)):
            return self.array

        return masked(self.array, self.fill_value)

    @property
    def values(self) -> NDArray | NDMaskedArray:
        """Compute and return the variable values as a NumPy array.

        Values matching a defined fill value are masked.

        Returns:
            The variable values, masked if a fill value is defined.
        """
        return self.compute()

    @values.setter
    def values(self, data: ArrayLike[Any]) -> None:
        """Replace the underlying Dask array.

        Masked input values are replaced using their fill value, which also
        becomes the variable's fill value. Unmasked input leaves it unchanged.

        Args:
            data: The new data.

        Raises:
            ValueError: If the number of data dimensions does not match the
                variable dimensions, or if the masked input has an incompatible
                fill value.
        """
        if len(data.shape) != len(self.dimensions):
            raise ValueError('Data shape does not match variable dimensions')
        self.array, self.fill_value = _as_dask_array(
            data, fill_value=self.fill_value)

    def persist(self, **kwargs) -> DelayedArray:
        """Persist the variable data in memory.

        Args:
            **kwargs: Arguments passed to the Dask persistence operation.

        Returns:
            The variable.
        """
        self.array = dask.base.persist(self.array, **kwargs)
        return self

    def compute(self, **kwargs) -> NDArray | NDMaskedArray:
        """Compute and return the variable values as a NumPy array.

        Values matching a defined fill value are masked.

        Args:
            **kwargs: Arguments passed to :func:`dask.compute`.
        """
        try:
            values: NDArray
            values, = dask.base.compute(self.array, traverse=False, **kwargs)
        except ValueError as exc:
            msg = str(exc)
            if 'cannot reshape' in msg or 'buffer too small' in msg:
                raise ModifiedVariableError from exc
            raise
        return (values if self.fill_value is None else masked(
            values, self.fill_value))

    def fill(self) -> DelayedArray:
        """Fill the variable with its fill value, if one is defined.

        Returns:
            The variable, unchanged if no fill value is defined.
        """
        if self.fill_value is not None:
            self.array = dask.array.creation.full_like(self.array,
                                                       self.fill_value)
        return self

    @classmethod
    def from_zarr(cls, array: zarr.Array, name: str, **kwargs) -> DelayedArray:
        """Create a delayed variable from a Zarr array.

        Args:
            array: The source Zarr array.
            name: The variable name.
            **kwargs: Additional arguments passed to
                :func:`zcollection.variable.delayed_array.from_zarr_array`.

        Returns:
            The new delayed variable.
        """
        attrs, fill_value = read_attributes(array)
        data: dask.array.core.Array = from_zarr_array(
            array,
            array.shape,
            array.chunks,
            name=f'{name}-{uuid.uuid1()}',
            **kwargs,
        )

        # Create a lazy Dask array instead of reading the Zarr data into memory.
        return cls(name,
                   data,
                   read_dimensions(array),
                   attrs=attrs,
                   compressor=read_compressor(array),
                   fill_value=fill_value,
                   filters=tuple(array.filters or ()))

    def concat(self, other: DelayedArray | Sequence[DelayedArray],
               dim: str) -> DelayedArray:
        """Concatenate the variable with other Dask-backed variables.

        Args:
            other: A variable or sequence of variables to concatenate.
            dim: The concatenation dimension.

        Returns:
            The concatenated variable.

        Raises:
            ValueError: If the sequence of variables is empty.
        """
        return concat(self, other, dask.array.core.concatenate, dim)

    def __getitem__(self, key: Any) -> Any:
        """Return the values selected by an index or slice.

        Args:
            key: The index or slice.

        Returns:
            The selected Dask array, masked if a fill value is defined.
        """
        return self.data[key]

    def rechunk(self, **kwargs) -> DelayedArray:
        """Rechunk the variable's Dask array.

        Args:
            **kwargs: Arguments passed to :func:`dask.array.rechunk`.

        Returns:
            The rechunked variable.
        """

        return self.duplicate(self.array.rechunk(**kwargs))

    def to_dask_array(self):
        """Return the underlying Dask array.

        Returns:
            The Dask array.

        .. seealso::

            :func:`dask.array.asarray`
        """
        return self.data

    def __dask_graph__(self) -> Mapping | None:
        """Return the Dask task graph."""
        return self.data.__dask_graph__()

    def __dask_keys__(self) -> list:
        """Return the output keys for the Dask graph."""
        return self.data.__dask_keys__()

    def __dask_layers__(self) -> Sequence[str]:
        """Return the layers for the Dask graph."""
        return self.data.__dask_layers__()

    def __dask_tokenize__(self) -> Any:
        """Return the token for the Dask graph."""
        return dask.base.normalize_token(
            (type(self), self.name, self.data, self.dimensions, self.attrs,
             self.fill_value))

    @staticmethod
    def __dask_optimize__(dsk: MutableMapping, keys: list,
                          **kwargs) -> MutableMapping:
        """Return the optimized Dask graph.

        .. seealso::

            :meth:`dask.array.Array.__dask_optimize__`
        """
        return dask.array.core.Array.__dask_optimize__(dsk, keys, **kwargs)

    #: Default scheduler used by this Dask collection.
    __dask_scheduler__ = staticmethod(dask.threaded.get)

    def _dask_finalize(self, results, array_func, *args,
                       **kwargs) -> DelayedArray:
        """Finalize the computation of the variable."""
        array: Any = array_func(results, *args, **kwargs)
        if not isinstance(array, dask.array.core.Array):
            array = dask.array.core.from_array(array)

        return self.duplicate(array)

    def __dask_postcompute__(self) -> tuple:
        """Return the finalizer and arguments used to convert computed results
        to their in-memory representation."""
        array_func: Callable
        array_args: tuple

        array_func, array_args = self.data.__dask_postcompute__()
        return self._dask_finalize, (array_func, *array_args)

    def __dask_postpersist__(self) -> tuple:
        """Return the rebuilder and arguments for persisted or rebuilt Dask
        graphs."""
        array_func: Callable
        array_args: tuple

        array_func, array_args = self.data.__dask_postpersist__()
        return self._dask_finalize, (array_func, *array_args)
